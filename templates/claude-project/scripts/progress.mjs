#!/usr/bin/env node
// Owns PLAN.md ticks and PROGRESS.md so agents never edit them by hand.
//
// Local models corrupt free-form status files: when an exact-match edit fails
// they append a fresh copy of the section instead, and two writers (main chat
// and subagent) both "update" the same file. This script is the only writer.
// PROGRESS.md is regenerated from PLAN.md and progress/ on every call, and
// "Next" is computed from PLAN.md, so it cannot go stale.
//
//   node scripts/progress.mjs                      regenerate PROGRESS.md, print Next + open notes
//   node scripts/progress.mjs done <id> --summary "..." --files "a.ts, b.css" \
//        [--decisions "..."] [--open "..."]        record a finished task, tick PLAN.md
//   node scripts/progress.mjs decision "<text>"    add a lasting decision
//   node scripts/progress.mjs note "<text>"        add an open note (review item, follow-up)
//   node scripts/progress.mjs resolve <n>          remove open note number <n>
//   node scripts/progress.mjs check                exit 1 if PLAN.md / progress/ / PROGRESS.md disagree
//
// Files: PLAN.md (task list, ticks), progress/<id>.md (one per finished task,
// written once), progress/decisions.md, progress/notes.md, PROGRESS.md (generated).
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const PLAN = path.join(ROOT, 'PLAN.md');
const DIR = path.join(ROOT, 'progress');
const OUT = path.join(ROOT, 'PROGRESS.md');
const DECISIONS = path.join(DIR, 'decisions.md');
const NOTES = path.join(DIR, 'notes.md');
const LOG_SHOWN = 6; // log entries shown in PROGRESS.md; the rest stay in progress/
const TASK_RE = /^- \[( |x)\] (\d+(?:\.\d+)+) (.*)$/;

const die = (msg) => { console.error(`progress: ${msg}`); process.exit(1); };
const read = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');
const today = () => new Date().toISOString().slice(0, 10);
const idKey = (id) => id.split('.').map(Number);
const cmpId = (a, b) => {
  const x = idKey(a), y = idKey(b);
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    const d = (x[i] ?? -1) - (y[i] ?? -1);
    if (d) return d;
  }
  return 0;
};

function planTasks() {
  if (!fs.existsSync(PLAN)) die('PLAN.md not found (run from the project root)');
  const tasks = [];
  read(PLAN).split('\n').forEach((line, i) => {
    const m = line.match(TASK_RE);
    if (m) tasks.push({ done: m[1] === 'x', id: m[2], title: m[3].trim(), line: i });
  });
  return tasks;
}

const bullets = (file) =>
  read(file).split('\n').filter((l) => l.startsWith('- ')).map((l) => l.slice(2));

function logEntries() {
  if (!fs.existsSync(DIR)) return [];
  return fs.readdirSync(DIR)
    .filter((f) => /^\d+(?:\.\d+)+\.md$/.test(f))
    .map((f) => ({ id: f.slice(0, -3), text: read(path.join(DIR, f)).trim() }))
    .sort((a, b) => cmpId(b.id, a.id));
}

function render() {
  const tasks = planTasks();
  const done = tasks.filter((t) => t.done);
  const next = tasks.find((t) => !t.done);
  const notes = bullets(NOTES);
  const decisions = bullets(DECISIONS);
  const log = logEntries();
  const lines = [
    '# Progress',
    '',
    '<!-- GENERATED by scripts/progress.mjs. Do not edit this file by hand: run',
    '     `node scripts/progress.mjs done <id> ...`, `note`, `resolve`, `decision`. -->',
    '',
    '## Next',
    next ? `${next.id} ${next.title} (see PLAN.md)` : 'All PLAN.md tasks are done.',
    '',
    '## State',
    `${done.length} of ${tasks.length} PLAN.md tasks done.` +
      (log[0] ? ` Last recorded: ${log[0].id}.` : ''),
    '',
    '## Open notes',
    ...(notes.length ? notes.map((n, i) => `${i + 1}. ${n}`) : ['None.']),
    '',
    '## Decisions',
    ...(decisions.length ? decisions.map((d) => `- ${d}`) : ['None yet.']),
    '',
    `## Log (newest ${Math.min(LOG_SHOWN, log.length)} of ${log.length}; all in progress/)`,
    '',
    ...log.slice(0, LOG_SHOWN).flatMap((e) => [e.text, '']),
  ];
  return lines.join('\n').replace(/\n+$/, '\n');
}

const write = () => fs.writeFileSync(OUT, render());

function parseFlags(args) {
  const flags = {}, rest = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a.startsWith('--')) {
      const eq = a.indexOf('=');
      if (eq > 0) flags[a.slice(2, eq)] = a.slice(eq + 1);
      else flags[a.slice(2)] = args[++i] ?? '';
    } else rest.push(a);
  }
  return { flags, rest };
}

const oneLine = (s) => String(s ?? '').replace(/\s*\n\s*/g, ' ').trim();

function cmdDone(args) {
  const { flags, rest } = parseFlags(args);
  const id = rest[0];
  if (!id) die('usage: done <id> --summary "..." --files "..." [--decisions "..."] [--open "..."]');
  const tasks = planTasks();
  const task = tasks.find((t) => t.id === id);
  if (!task) die(`task ${id} is not in PLAN.md (ids: ${tasks.map((t) => t.id).join(', ')})`);
  if (!flags.summary) die('--summary is required (one line: what was done)');
  fs.mkdirSync(DIR, { recursive: true });
  const file = path.join(DIR, `${id}.md`);
  if (fs.existsSync(file) && !('amend' in flags)) die(`${id} is already recorded; pass --amend to replace it`);
  const entry = [
    `### ${today()} ${id} ${task.title}`,
    `- Summary: ${oneLine(flags.summary)}`,
    `- Files: ${oneLine(flags.files) || 'none listed'}`,
    `- Decisions: ${oneLine(flags.decisions) || 'none'}`,
    `- Open: ${oneLine(flags.open) || 'none'}`,
  ].join('\n');
  fs.writeFileSync(file, entry + '\n');
  if (!task.done) {
    const lines = read(PLAN).split('\n');
    lines[task.line] = lines[task.line].replace('- [ ]', '- [x]');
    fs.writeFileSync(PLAN, lines.join('\n'));
  }
  write();
  const next = planTasks().find((t) => !t.done);
  console.log(`recorded ${id}; PLAN.md ticked; PROGRESS.md regenerated. Next: ${next ? `${next.id} ${next.title}` : 'none'}`);
}

function appendBullet(file, text) {
  const t = oneLine(text);
  if (!t) die('text is required');
  fs.mkdirSync(DIR, { recursive: true });
  const body = read(file);
  fs.writeFileSync(file, (body && !body.endsWith('\n') ? body + '\n' : body) + `- ${t} (${today()})\n`);
  write();
}

function cmdResolve(n) {
  const notes = bullets(NOTES);
  const i = Number(n) - 1;
  if (!Number.isInteger(i) || i < 0 || i >= notes.length) die(`no open note ${n} (there are ${notes.length})`);
  notes.splice(i, 1);
  fs.writeFileSync(NOTES, notes.map((x) => `- ${x}\n`).join(''));
  write();
  console.log(`resolved note ${n}`);
}

function cmdCheck() {
  const problems = [];
  const tasks = planTasks();
  const seen = new Set();
  for (const t of tasks) {
    if (seen.has(t.id)) problems.push(`PLAN.md lists task ${t.id} twice`);
    seen.add(t.id);
  }
  const logged = new Set(logEntries().map((e) => e.id));
  for (const t of tasks) {
    if (t.done && !logged.has(t.id)) problems.push(`${t.id} is ticked in PLAN.md but has no progress/${t.id}.md (record it with \`done ${t.id} ...\`)`);
    if (!t.done && logged.has(t.id)) problems.push(`progress/${t.id}.md exists but ${t.id} is not ticked in PLAN.md`);
  }
  for (const id of logged) if (!seen.has(id)) problems.push(`progress/${id}.md has no matching PLAN.md task`);
  if (read(OUT) !== render()) problems.push('PROGRESS.md was edited by hand or is stale: run `node scripts/progress.mjs` to regenerate it');
  if (problems.length) {
    console.error('progress check FAILED:\n' + problems.map((p) => `- ${p}`).join('\n'));
    process.exit(1);
  }
  console.log(`progress check passed (${tasks.filter((t) => t.done).length}/${tasks.length} done)`);
}

const [cmd, ...args] = process.argv.slice(2);
switch (cmd) {
  case undefined:
  case 'show': {
    write();
    const next = planTasks().find((t) => !t.done);
    console.log(`Next: ${next ? `${next.id} ${next.title}` : 'all tasks done'}`);
    bullets(NOTES).forEach((n, i) => console.log(`Note ${i + 1}: ${n}`));
    break;
  }
  case 'done': cmdDone(args); break;
  case 'decision': appendBullet(DECISIONS, args.join(' ')); console.log('decision recorded'); break;
  case 'note': appendBullet(NOTES, args.join(' ')); console.log('note added'); break;
  case 'resolve': cmdResolve(args[0]); break;
  case 'check': cmdCheck(); break;
  default: die(`unknown command "${cmd}" (show | done | decision | note | resolve | check)`);
}
